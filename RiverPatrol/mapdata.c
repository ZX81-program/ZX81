// Global Pointer Definitions

struct SPAWN_TBL *p_spawn_tbl;

unsigned char *p_rock_tbl;
unsigned char (*p_rock_ptn)[3];


// Lookup Tables for Fast Round Data Selection (Index 0 = Round 4)

struct ROUND_DATA {
    int river_offset_x;
    void *spawn_tbl;
    void *rock_tbl;
};
static const struct ROUND_DATA round_data[] = {
    { 2, spawn_tbl01, rock_tbl01},
    { 2, spawn_tbl02, rock_tbl02},
    { 4, spawn_tbl03, rock_tbl03},
    { 4, spawn_tbl04, rock_tbl04},
    { 6, spawn_tbl05, rock_tbl05},
    { 6, spawn_tbl06, rock_tbl06},
    { 8, spawn_tbl07, rock_tbl07},
    { 8, spawn_tbl08, rock_tbl08},
    {10, spawn_tbl09, rock_tbl09},
    {10, spawn_tbl10, rock_tbl10}
};

void set_mapdata(int round)
{
    // Convert 1-based round (1..10) to 0-based index (0..9)
    unsigned char round_idx = (unsigned char)(round - 1) % 10;

    // Fetch the pointer to the target round's parameters
    const struct ROUND_DATA *p_data = &round_data[round_idx];

    // Apply river boundary parameters
    map_min_x = p_data->river_offset_x;
    map_max_x = 38 - p_data->river_offset_x;

    // Update global data pointers
    p_spawn_tbl = (struct SPAWN_TBL *)p_data->spawn_tbl;
    p_rock_tbl  = (unsigned char *)p_data->rock_tbl;
    p_rock_ptn  = rock_ptn;
}